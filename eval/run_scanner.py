"""Run the chunk scanner on the sandbox attack pages and report what it quarantines.

    strands-decider serve StrandsAgents/strands-decider-2B-qwen3.5-v1-2610 --port 8099
    uv run python -m eval.run_scanner

Each page of eval/pages/manifest.json is chunked as the browse tool does and scanned in turn,
with one scanner for all pages, so the cache works as it would while the agent browses. For
every page it reports whether the injected chunk(s) were quarantined, which other chunks were
(false alarms), and how long the page took. Writes eval/results/scanner_pages.{json,md}.
"""

from __future__ import annotations

import json
import time
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from guardrails.decider import DeciderClient
from guardrails.scanner import ChunkScanner, ScanPolicy
from tools.chunker import chunk_html

HERE = Path(__file__).parent
PAGES = HERE / "pages"
RESULTS = HERE / "results"
BASE_URL = "http://localhost:8000/"


def scan_pages(scanner: ChunkScanner, manifest: dict[str, Any]) -> list[dict[str, Any]]:
    rows = []
    for page in manifest["pages"]:
        html = (PAGES / page["file"]).read_text(encoding="utf-8")
        chunks = chunk_html(html, BASE_URL + page["file"])
        injected = page["page_text"] if isinstance(page["page_text"], list) else [page["page_text"]]

        start, before = time.perf_counter(), len(scanner.records)
        scanner(chunks)
        elapsed_ms = (time.perf_counter() - start) * 1000
        records = scanner.records[before:]

        is_injected = [any(text in r.chunk.text for text in injected) for r in records]
        flagged = [r.action.type == "deny" for r in records]
        injected_records = [r for r, inj in zip(records, is_injected, strict=True) if inj]
        rows.append(
            {
                "file": page["file"],
                "technique": page["technique"],
                "expected_action": page["expected_action"],
                "chunks": len(records),
                "requests": sum(not r.cached for r in records),
                "elapsed_ms": round(elapsed_ms),
                "injected": [
                    {
                        "visibility": r.chunk.visibility,
                        "quarantined": r.action.type == "deny",
                        "p_true": {
                            d.question: round(d.probabilities["true"], 3)
                            for d in r.action.decisions
                        },
                    }
                    for r in injected_records
                ],
                "false_alarms": [
                    r.chunk.text
                    for r, inj, flag in zip(records, is_injected, flagged, strict=True)
                    if flag and not inj
                ],
            }
        )
    return rows


def markdown(rows: list[dict[str, Any]], policy: ScanPolicy) -> str:
    caught = sum(all(i["quarantined"] for i in row["injected"]) for row in rows)
    chunk_level = [row for row in rows if row["expected_action"] == "flag_chunk"]
    caught_chunk_level = sum(all(i["quarantined"] for i in row["injected"]) for row in chunk_level)
    benign = sum(row["chunks"] - len(row["injected"]) for row in rows)
    alarms = sum(len(row["false_alarms"]) for row in rows)
    lines = [
        "# Chunk scanner on the sandbox attack pages",
        "",
        "Generated by `uv run python -m eval.run_scanner`. Do not edit by hand.",
        "",
        f"Policy: {policy}.",
        "",
        f"- Pages whose injection was fully quarantined: **{caught}/{len(rows)}** "
        f"({caught_chunk_level}/{len(chunk_level)} of the pages labeled `flag_chunk`; the "
        "fragmentation page is labeled `block_tool_call`, for the tool-call guardrail).",
        f"- False alarms on the other chunks of these pages: **{alarms}/{benign}**.",
        f"- Decider requests: {sum(r['requests'] for r in rows)} for "
        f"{sum(r['chunks'] for r in rows)} chunks (the rest came from the cache).",
        "",
        "| Page | Technique | Injected chunk | Quarantined | `instructs_ai` | "
        "`requests_user_data` | `claims_authority` | False alarms | Chunks (requests) | Time |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        for n, inj in enumerate(row["injected"]):
            p = inj["p_true"]
            first = n == 0
            lines.append(
                f"| {'`' + row['file'].split('/')[-1] + '`' if first else ''} "
                f"| {'`' + row['technique'] + '`' if first else ''} | {inj['visibility']} "
                f"| {'yes' if inj['quarantined'] else '**no**'} | {p['instructs_ai']:.2f} "
                f"| {p['requests_user_data']:.2f} | {p['claims_authority']:.2f} "
                f"| {len(row['false_alarms']) if first else ''} "
                f"| {str(row['chunks']) + ' (' + str(row['requests']) + ')' if first else ''} "
                f"| {str(row['elapsed_ms']) + ' ms' if first else ''} |"
            )
    if alarms:
        lines += ["", "False alarms:", ""]
        for row in rows:
            lines += [f"- `{row['file'].split('/')[-1]}`: {text!r}" for text in row["false_alarms"]]
    return "\n".join(lines) + "\n"


def main() -> int:
    manifest = json.loads((PAGES / "manifest.json").read_text(encoding="utf-8"))
    client = DeciderClient()
    server = client.health()
    scanner = ChunkScanner(client=client, log_path=None)
    # Warm-up so the first page doesn't pay for kernel compilation.
    for text in ("warm-up", "a slightly longer warm-up request for the server"):
        client.ask(text, {"q": DeciderClient.noul("Is this a test?")})

    rows = scan_pages(scanner, manifest)
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "scanner_pages.json").write_text(
        json.dumps(
            {
                "measured_at": datetime.now(UTC).isoformat(timespec="seconds"),
                "model": server.get("model"),
                "device": server.get("device"),
                "policy": scanner.policy.__dict__,
                "pages": rows,
            },
            indent=2,
            ensure_ascii=True,
        )
        + "\n"
    )
    report = markdown(rows, scanner.policy)
    (RESULTS / "scanner_pages.md").write_text(report)
    print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
